package dev.mcwebclient.baker;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

import net.fabricmc.loader.api.FabricLoader;
import net.fabricmc.loader.api.ModContainer;
import net.fabricmc.loader.api.metadata.ModMetadata;
import net.fabricmc.loader.impl.metadata.EntrypointMetadata;
import net.fabricmc.loader.impl.metadata.LoaderModMetadata;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;
import org.objectweb.asm.tree.MethodNode;

/**
 * Generates {@code BakedEntrypoints.java}: every Fabric entrypoint as plain Java.
 *
 * <p>Fabric's default language adapter creates entrypoints reflectively; a method
 * reference ({@code Class::method}) becomes a {@code MethodHandleProxies} proxy class,
 * which an ahead-of-time image can't define at run time. The generated table builds
 * the same objects with {@code new}, lambdas and field reads instead. Members it can't
 * reach from generated code (non-public) are left to the runtime's reflective fallback,
 * and listed in the report.</p>
 */
final class EntrypointTable {
    /** Entrypoint keys whose interface is fixed by Fabric; needed to turn method references into lambdas. */
    private static final Map<String, String> KEY_INTERFACES = Map.of(
            "main", "net.fabricmc.api.ModInitializer",
            "client", "net.fabricmc.api.ClientModInitializer",
            "server", "net.fabricmc.api.DedicatedServerModInitializer",
            "preLaunch", "net.fabricmc.loader.api.entrypoint.PreLaunchEntrypoint");

    private final Function<String, byte[]> classBytes;
    private final List<String> notes = new ArrayList<>();

    EntrypointTable(Function<String, byte[]> classBytes) {
        this.classBytes = classBytes;
    }

    List<String> notes() {
        return notes;
    }

    void write(FabricLoader loader, Path sourceRoot, java.util.Set<String> skipMods) throws IOException {
        // value -> (interface or "" for any type) -> Java expression
        Map<String, Map<String, String>> cases = new LinkedHashMap<>();
        for (ModContainer mod : loader.getAllMods()) {
            ModMetadata meta = mod.getMetadata();
            if (skipMods.contains(meta.getId()) || !(meta instanceof LoaderModMetadata lmm)) {
                continue;
            }
            for (String key : lmm.getEntrypointKeys()) {
                for (EntrypointMetadata ep : lmm.getEntrypoints(key)) {
                    String where = meta.getId() + " " + key + " " + ep.getValue();
                    if (!"default".equals(ep.getAdapter())) {
                        notes.add("adapter " + ep.getAdapter() + " not baked: " + where);
                        continue;
                    }
                    String iface = KEY_INTERFACES.getOrDefault(key, "");
                    String expr = expression(ep.getValue(), iface, where);
                    if (expr != null) {
                        cases.computeIfAbsent(ep.getValue(), v -> new LinkedHashMap<>()).put(iface, expr);
                    }
                }
            }
        }

        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by tools/fabric-baker (EntrypointTable). Do not edit.\n");
        sb.append("package dev.mcwebclient.web.fabric.gen;\n\n");
        sb.append("@SuppressWarnings({\"all\"})\n");
        sb.append("public final class BakedEntrypoints {\n");
        sb.append("    private BakedEntrypoints() {\n    }\n\n");
        sb.append("    /** Returns the entrypoint object for {@code value}, or null if it isn't baked. */\n");
        sb.append("    public static Object create(String value, Class<?> type) throws Exception {\n");
        sb.append("        switch (value) {\n");
        for (Map.Entry<String, Map<String, String>> c : cases.entrySet()) {
            sb.append("            case ").append(literal(c.getKey())).append(": {\n");
            for (Map.Entry<String, String> e : c.getValue().entrySet()) {
                if (e.getKey().isEmpty()) {
                    sb.append("                return ").append(e.getValue()).append(";\n");
                } else {
                    sb.append("                if (type == ").append(e.getKey()).append(".class) {\n");
                    sb.append("                    return ").append(e.getValue()).append(";\n");
                    sb.append("                }\n");
                }
            }
            if (!c.getValue().containsKey("")) {
                sb.append("                return null;\n");
            }
            sb.append("            }\n");
        }
        sb.append("            default:\n                return null;\n        }\n    }\n}\n");

        Path file = sourceRoot.resolve("dev/mcwebclient/web/fabric/gen/BakedEntrypoints.java");
        Files.createDirectories(file.getParent());
        Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
    }

    /** Java expression creating the entrypoint, or null (reported) if generated code can't reach it. */
    private String expression(String value, String iface, String where) {
        String[] parts = value.split("::");
        String className = parts[0];
        ClassNode cls = node(className);
        if (cls == null) {
            notes.add("class not in bake: " + where);
            return null;
        }
        String src = sourceName(cls);
        if (src == null) {
            notes.add("class not accessible: " + where);
            return null;
        }
        if (parts.length == 1) {
            return publicNoArgConstructor(cls) ? "new " + src + "()" : note("no public no-arg constructor: " + where);
        }
        if (parts.length != 2) {
            return note("malformed: " + where);
        }
        String member = parts[1];
        for (FieldNode f : cls.fields) {
            if (f.name.equals(member)) {
                boolean ok = (f.access & Opcodes.ACC_STATIC) != 0 && (f.access & Opcodes.ACC_PUBLIC) != 0;
                return ok ? src + "." + member : note("field not public static: " + where);
            }
        }
        if (iface.isEmpty()) {
            return note("method reference with unknown interface type: " + where);
        }
        MethodNode target = null;
        for (MethodNode m : cls.methods) {
            if (m.name.equals(member)) {
                if (target != null) {
                    return note("overloaded method: " + where);
                }
                target = m;
            }
        }
        if (target == null) {
            return note("member not found: " + where);
        }
        if ((target.access & Opcodes.ACC_PUBLIC) == 0) {
            return note("method not public: " + where);
        }
        if ((target.access & Opcodes.ACC_STATIC) != 0) {
            return "(" + iface + ") " + src + "::" + member;
        }
        return publicNoArgConstructor(cls)
                ? "(" + iface + ") new " + src + "()::" + member
                : note("instance method without public no-arg constructor: " + where);
    }

    private String note(String s) {
        notes.add(s);
        return null;
    }

    private ClassNode node(String binaryName) {
        byte[] bytes = classBytes.apply(binaryName.replace('.', '/'));
        if (bytes == null) {
            return null;
        }
        ClassNode node = new ClassNode();
        new ClassReader(bytes).accept(node, ClassReader.SKIP_CODE | ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES);
        return node;
    }

    /** Canonical source name if the class (and every enclosing class) is public, else null. */
    private String sourceName(ClassNode cls) {
        if ((cls.access & Opcodes.ACC_PUBLIC) == 0) {
            return null;
        }
        String name = cls.name;
        for (var inner : cls.innerClasses) {
            if (inner.name.equals(cls.name)) {
                if (inner.outerName == null || (inner.access & Opcodes.ACC_PUBLIC) == 0) {
                    return null; // local/anonymous or non-public member class
                }
                ClassNode outer = node(inner.outerName.replace('/', '.'));
                String outerSrc = outer == null ? null : sourceName(outer);
                return outerSrc == null ? null : outerSrc + "." + inner.innerName;
            }
        }
        return name.replace('/', '.');
    }

    private static boolean publicNoArgConstructor(ClassNode cls) {
        if ((cls.access & (Opcodes.ACC_ABSTRACT | Opcodes.ACC_INTERFACE)) != 0) {
            return false;
        }
        for (MethodNode m : cls.methods) {
            if (m.name.equals("<init>") && m.desc.equals("()V")) {
                return (m.access & Opcodes.ACC_PUBLIC) != 0;
            }
        }
        return false;
    }

    private static String literal(String s) {
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
